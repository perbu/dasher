#!/usr/bin/env bash
# Bakes the MQTT credentials into the firmware as firmware/src/certs.h.
#
# Usage:
#   scripts/gen-firmware-certs.sh [device-name]     default: esp32
#
# Emits the CA the device trusts (certs/ca.crt) plus its own client
# certificate and key, as C string literals. The generated header contains a
# private key, so it is git-ignored — regenerate it rather than committing it.
set -euo pipefail

cd "$(dirname "$0")/.."
name="${1:-esp32}"
out="firmware/src/certs.h"

for f in "certs/ca.crt" "certs/$name.crt" "certs/$name.key"; do
  if [[ ! -f "$f" ]]; then
    echo "missing $f — run 'scripts/mqtt-client-ca.sh issue $name' first" >&2
    exit 1
  fi
done

emit() { # emit <symbol> <pem-file>
  printf 'static const char %s[] = R"EOF(\n' "$1"
  cat "$2"
  printf ')EOF";\n\n'
}

{
  printf '// Generated by scripts/gen-firmware-certs.sh — do not edit, do not commit.\n'
  printf '// Holds the private key for MQTT client %s.\n\n' "$name"
  printf '#pragma once\n\n'
  emit kMqttCaCert "certs/ca.crt"
  emit kMqttClientCert "certs/$name.crt"
  emit kMqttClientKey "certs/$name.key"
} >"$out"

chmod 600 "$out"
echo "wrote $out for client '$name' (git-ignored; holds a private key)"
